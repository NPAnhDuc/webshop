"""Build (question, positive fragment, hard negatives) data for an evidence reranker.

Labels come only from the knowledge store/catalog records (which mirror the shop DB):
- product field questions: positive = the exact record line; negatives = other lines of the
  SAME product (teaches field choice) + same field of other products (teaches entity binding);
- knowledge questions: document/section headings and, optionally, questions generated by the
  local model FROM a fragment (stage --generate); positive = that fragment, negatives = other
  fragments of the same and of lexically similar documents.
Evaluation banks (479 quality loop, 300 buyer, handbook/period banks) are excluded by exact and
near-duplicate matching and their templates are not reused. Products and documents are split
train/dev by entity so dev measures generalisation, not memorisation.
"""
import argparse
import hashlib
import json
import random
import re
import sys
from datetime import date
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from shopbot.knowledge import KnowledgeStore
from shopbot.monthly import active_documents,atomic_json
from shopbot.rag_answer import evidence_fragments
from shopbot.chunking import chunk_document
from shopbot.retrieval import normalize

OUT=ROOT/'data/finetune_20261024'
DB=ROOT/'data/business_sql/scenario_v1/shop.sqlite'
TODAY=date(2026,10,24)
PHRASES={  # Vietnamese ways customers name the English catalog labels
 'Processor Brand':['hãng CPU','CPU của hãng nào'],'Processor Model':['tên CPU','model vi xử lý','chip gì'],
 'Processor Core':['số nhân CPU','CPU mấy nhân','bao nhiêu nhân'],'RAM':['dung lượng RAM','RAM bao nhiêu'],
 'RAM Type':['loại RAM','RAM chuẩn gì'],'Installed SSD Type':['ổ SSD','dung lượng ổ cứng'],
 'Graphics Chipset':['card đồ họa','GPU gì'],'Graphics Memory Accessibility':['card rời hay tích hợp','đồ họa tích hợp hay rời'],
 'Graphics Memory':['bộ nhớ đồ họa','VRAM bao nhiêu'],'Display Size (Inch)':['màn hình mấy inch','kích thước màn hình'],
 'Display Type':['loại màn hình','tấm nền màn hình'],'Display Resolution':['độ phân giải màn hình','màn hình độ phân giải bao nhiêu'],
 'Touch Screen':['màn hình cảm ứng không','có cảm ứng không'],'Optical Drive':['ổ đĩa quang','có ổ DVD không'],
 'LAN':['cổng mạng LAN','có cổng LAN không'],'Finger Print Sensor':['cảm biến vân tay','có vân tay không'],
 'Operating System':['hệ điều hành','cài sẵn Windows không'],'HDMI Port':['cổng HDMI','có HDMI không'],
 'Power Adapter':['sạc bao nhiêu W','bộ sạc'],'Weight (Kg)':['nặng bao nhiêu','trọng lượng'],
}
TEMPLATES=['{p} {f} là gì?','Cho mình hỏi {f} của {p}.','{f} trên {p} ra sao?','Mình muốn biết {p} có {f} thế nào',
           'Thông tin {f} của {p}?','{p}: {f}?','Shop cho em xin {f} của {p} với','Về {p}, {f} thì sao?']
EXCLUDED_TEMPLATES=('theo danh muc tham khao','nhac lai','san pham vua noi','chi dung du lieu da luu')


def key(text):return re.sub(r'\W+',' ',normalize(text)).strip()


def evaluation_questions():
    texts=[]
    for b in json.loads((ROOT/'evaluation/quality_loop_20261021/bank.json').read_text(encoding='utf8')):texts.append(b['question'])
    for line in (ROOT/'evaluation/buyer_expansion_20261024_r2/bank.jsonl').read_text(encoding='utf8').splitlines():
        if line.strip():texts.append(json.loads(line)['question'])
    for path in ['evaluation/handbook_20261024_after2/results.json','evaluation/period_20261024_after/results.json']:
        texts+=[r['question'] for r in json.loads((ROOT/path).read_text(encoding='utf8'))]
    return {key(t) for t in texts}


def split_of(identifier):
    return 'dev' if int(hashlib.sha256(identifier.encode()).hexdigest(),16)%7==0 else 'train'


def product_examples(products,rng):
    lines={}
    for d in products:
        rows=[l for l in d['text'].splitlines() if l.startswith(d['title']+': ')]
        lines[d['document_id']]={l[len(d['title'])+2:].split(':',1)[0].strip():l for l in rows}
    out=[]
    for d in products:
        fields=lines[d['document_id']]
        for label,line in fields.items():
            phrases=PHRASES.get(label,[label])
            for phrase in phrases:
                template=rng.choice(TEMPLATES)
                query=template.format(p=d['title'],f=phrase)
                same=[l for other,l in fields.items() if other!=label]
                cross=[lines[o][label] for o in lines if o!=d['document_id'] and label in lines[o]]
                out.append(dict(query=query,positive=line,negatives=rng.sample(same,min(6,len(same)))+rng.sample(cross,min(2,len(cross))),
                                origin='product_field',entity=d['document_id'],label=label,split=split_of(d['document_id'])))
    return out


def knowledge_examples(docs,rng):
    out=[]
    by_doc={}
    for d in docs:
        frags=[f['text'] for f in evidence_fragments(chunk_document(d,max_words=100)).values() if len(f['text'].split())>=6]
        if frags:by_doc[d['document_id']]=(d,frags)
    ids=list(by_doc)
    for doc_id,(d,frags) in by_doc.items():
        chunks=chunk_document(d,max_words=100)
        for chunk in chunks:
            heading=chunk['heading_path'].split(' > ')[-1].strip(' #')
            question=heading if heading.endswith('?') else None
            if not question:continue
            positives=[f['text'] for f in evidence_fragments([chunk]).values() if len(f['text'].split())>=6]
            if not positives:continue
            others=[f for f in frags if f not in positives]
            foreign=[f for o in rng.sample(ids,min(4,len(ids))) if o!=doc_id for f in by_doc[o][1][:3]]
            for positive in positives[:2]:
                out.append(dict(query=question,positive=positive,negatives=rng.sample(others,min(4,len(others)))+foreign[:4],
                                origin='section_heading',entity=doc_id,split=split_of(doc_id)))
    return out,by_doc


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--seed',type=int,default=20261024);args=parser.parse_args()
    rng=random.Random(args.seed)
    store=KnowledgeStore(DB);docs=active_documents(store.all_records(),'admin',store.kind,TODAY)
    products=[d for d in docs if d['doc_type']=='product'];knowledge=[d for d in docs if d['doc_type']!='product']
    rows=product_examples(products,rng);more,by_doc=knowledge_examples(knowledge,rng);rows+=more
    banned=evaluation_questions();kept=[];dropped=0
    for r in rows:
        k=key(r['query'])
        if k in banned or any(t in k for t in EXCLUDED_TEMPLATES):dropped+=1;continue
        kept.append(r)
    OUT.mkdir(parents=True,exist_ok=True)
    for split in ('train','dev'):
        with (OUT/f'{split}.jsonl').open('w',encoding='utf8') as f:
            for r in kept:
                if r['split']==split:f.write(json.dumps(r,ensure_ascii=False)+'\n')
    card=dict(created=TODAY.isoformat(),seed=args.seed,database=str(DB),
              counts={s:sum(r['split']==s for r in kept) for s in ('train','dev')},
              by_origin={o:sum(r['origin']==o for r in kept) for o in {r['origin'] for r in kept}},
              dropped_as_evaluation_overlap=dropped,products=len(products),knowledge_documents=len(by_doc),
              labels_from='knowledge store records only (mirror shop DB/catalog/sourced docs); no model answers, no evaluation questions',
              split='by entity (product/document) hash; dev entities never appear in train')
    atomic_json(OUT/'DATA_CARD.json',card);print(json.dumps(card,ensure_ascii=False,indent=1))


if __name__=='__main__':main()
